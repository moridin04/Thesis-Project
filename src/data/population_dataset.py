import pandas as pd
import numpy as np

df = pd.read_csv('/content/population-dataset.csv', header=None)
df.columns = ["Barangay", "Population"]
print(df.head())

df.columns = ["Barangay", "Population"]
print(df.head())

df.duplicated().sum()
df.shape

df_flood = pd.read_csv('/content/MetroManila_Barangay_Flood_Area_Validated.csv', header=None)
df_flood.columns = ["Barangay", "Barangay Area Sqm", "Flood Area 5yr Sqm", "Flood PCT 5yr", "Flood Area 25yr Sqm", "Flood PCT 25yr", "Flood Area 100yr Sqm", "Flood PCT 100yr", "Flag 25yr Less than 5yr", "Flag 100yr Less than 25yr", "Flag 100yr Less than 5yr", "Barangay No"]
df_flood = df_flood.iloc[1:]
df_flood.head(5)

df_combined = pd.merge(df, df_flood, on='Barangay', how='inner')
print(df_combined.head())

df_combined['Population'] = pd.to_numeric(df_combined['Population'], errors='coerce')
df_combined['Barangay Area Sqm'] = pd.to_numeric(df_combined['Barangay Area Sqm'], errors='coerce')
df_combined['Flood Area 5yr Sqm'] = pd.to_numeric(df_combined['Flood Area 5yr Sqm'], errors='coerce')
df_combined['Flood PCT 5yr'] = pd.to_numeric(df_combined['Flood PCT 5yr'], errors='coerce')
df_combined['Flood Area 25yr Sqm'] = pd.to_numeric(df_combined['Flood Area 25yr Sqm'], errors='coerce')
df_combined['Flood PCT 25yr'] = pd.to_numeric(df_combined['Flood PCT 25yr'], errors='coerce')
df_combined['Flood Area 100yr Sqm'] = pd.to_numeric(df_combined['Flood Area 100yr Sqm'], errors='coerce')
df_combined['Flood PCT 100yr'] = pd.to_numeric(df_combined['Flood PCT 100yr'], errors='coerce')

df_combined_sorted = df_combined.sort_values(by='Barangay').reset_index(drop=True)
display(df_combined_sorted.head())

df_combined_sorted['Barangay_Num'] = df_combined_sorted['Barangay'].str.extract(r'(\d+)').astype(int)
df_combined_sorted = df_combined_sorted.sort_values(by='Barangay_Num').drop(columns=['Barangay_Num']).reset_index(drop=True)
display(df_combined_sorted.head())

import re

# Function to extract numeric part for proper sorting
def extract_number(text):
    match = re.search(r'(\d+)', str(text))
    return int(match.group()) if match else 0

# Sort the main dataframe permanently
df_combined['Sort_Key'] = df_combined['Barangay'].apply(extract_number)
df_combined = df_combined.sort_values(by='Sort_Key').drop(columns=['Sort_Key']).reset_index(drop=True)

# Display a sample from the middle to show 600+ range
print("Sample of the sorted data (Rows 595 to 605):")
display(df_combined.iloc[595:605])

#Population Density = population / barangay area

#Affected Population 5yr = population x floodpct5yr / 100

#Affected Population 25yr = population x floodpct25yr / 100

#Affected Population 100yr = population x floodpct100yr / 100

#Flood Escalation 5 to 25 = FloodPct25yr - FloodPct5yr

#Flood Escalation 25 to 100 = FloodPct100yr - FloodPct25yr

#Flood Escalation 5 to 100 = FloodPct100yr - FloodPct5yr

#Flood Severity Increase 5 to 25 = FloodArea25yr - FloodArea5yr

#Flood Severity Increase 25 to 100 = FloodArea100yr - FloodArea25yr

#Flood Severity Increase 5 to 100 = FloodArea100yr - FloodArea5yr

#Affected Population Increase 5 to 25 = AffectedPopulation25yr - AffectedPopulation5yr

#Affected Population Increase 25 to 100 = AffectedPopulation100yr - AffectedPopulation25yr

#Affected Population Increase 5 to 100 = AffectedPopulation100yr - AffectedPopulation5yr

#Flood Ratio 5yr = FloodPct5yr / 100

#Flood Ratio 25yr = FloodPct25yr / 100

#Flood Ratio 100yr = FloodPct100yr / 100

# ============================================================
# 1. Population Density
# ============================================================

# Population density per square meter
df_combined["Population Density per Sqm"] = np.where(
    df_combined["Barangay Area Sqm"] > 0,
    df_combined["Population"] / df_combined["Barangay Area Sqm"],
    0
)

# Population density per hectare
# 1 hectare = 10,000 square meters
df_combined["Population Density per Hectare"] = np.where(
    df_combined["Barangay Area Sqm"] > 0,
    df_combined["Population"] / (df_combined["Barangay Area Sqm"] / 10000),
    0
)


# ============================================================
# 2. Flood Ratios
# ============================================================

df_combined["Flood Ratio 5yr"] = df_combined["Flood PCT 5yr"] / 100
df_combined["Flood Ratio 25yr"] = df_combined["Flood PCT 25yr"] / 100
df_combined["Flood Ratio 100yr"] = df_combined["Flood PCT 100yr"] / 100


# ============================================================
# 3. Affected Population
# ============================================================

df_combined["Affected Population 5yr"] = (
    df_combined["Population"] * df_combined["Flood Ratio 5yr"]
)

df_combined["Affected Population 25yr"] = (
    df_combined["Population"] * df_combined["Flood Ratio 25yr"]
)

df_combined["Affected Population 100yr"] = (
    df_combined["Population"] * df_combined["Flood Ratio 100yr"]
)


# Optional: round affected population to nearest whole person
df_combined["Affected Population 5yr"] = df_combined["Affected Population 5yr"].round(0).astype("Int64")
df_combined["Affected Population 25yr"] = df_combined["Affected Population 25yr"].round(0).astype("Int64")
df_combined["Affected Population 100yr"] = df_combined["Affected Population 100yr"].round(0).astype("Int64")


# ============================================================
# 4. Flood Escalation
# ============================================================

df_combined["Flood Escalation 5to25"] = (
    df_combined["Flood PCT 25yr"] - df_combined["Flood PCT 5yr"]
)

df_combined["Flood Escalation 25to100"] = (
    df_combined["Flood PCT 100yr"] - df_combined["Flood PCT 25yr"]
)

df_combined["Flood Escalation 5to100"] = (
    df_combined["Flood PCT 100yr"] - df_combined["Flood PCT 5yr"]
)


# ============================================================
# 5. Flood Severity Increase
# ============================================================

df_combined["Flood Severity Increase 5to25 Sqm"] = (
    df_combined["Flood Area 25yr Sqm"] - df_combined["Flood Area 5yr Sqm"]
)

df_combined["Flood Severity Increase 25to100 Sqm"] = (
    df_combined["Flood Area 100yr Sqm"] - df_combined["Flood Area 25yr Sqm"]
)

df_combined["Flood Severity Increase 5to100 Sqm"] = (
    df_combined["Flood Area 100yr Sqm"] - df_combined["Flood Area 5yr Sqm"]
)


# ============================================================
# 6. Affected Population Increase
# ============================================================

df_combined["Affected Population Increase 5to25"] = (
    df_combined["Affected Population 25yr"] - df_combined["Affected Population 5yr"]
)

df_combined["Affected Population Increase 25to100"] = (
    df_combined["Affected Population 100yr"] - df_combined["Affected Population 25yr"]
)

df_combined["Affected Population Increase 5to100"] = (
    df_combined["Affected Population 100yr"] - df_combined["Affected Population 5yr"]
)

# ============================================================
# 7. 100-Year Validation Flags
# ============================================================

df_combined["Flag 25yr Less than 5yr"] = (
    df_combined["Flood PCT 25yr"] < df_combined["Flood PCT 5yr"]
)

df_combined["Flag 100yr Less than 25yr"] = (
    df_combined["Flood PCT 100yr"] < df_combined["Flood PCT 25yr"]
)

df_combined["Flag 100yr Less than 5yr"] = (
    df_combined["Flood PCT 100yr"] < df_combined["Flood PCT 5yr"]
)


# Optional readable data quality note
df_combined["100yr Data Quality Note"] = np.where(
    df_combined["Flag 100yr Less than 25yr"] | df_combined["Flag 100yr Less than 5yr"],
    "Review 100yr value: lower than expected return-period progression",
    "OK"
)

df_combined.to_csv('manila-city-flood-population_data.csv', index=False)
print('DataFrame exported to manila-city-flood-population_data.csv')

df_combined.to_excel('manila-city-flood-population.xlsx', index=False)
